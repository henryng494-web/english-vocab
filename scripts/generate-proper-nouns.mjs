const proper = new Set();
for (const entry of subtlex) {
  const raw = String(entry.word ?? "");
  if (!/^[A-Z]/.test(raw) || raw === "I") continue;
  const word = raw.toLowerCase();
  if (!/^[a-z]+$/.test(word) || word.length < 2) continue;
  if (ngsl.has(word) || CURRICULUM.has(word) || KEEP_COMMON.has(word)) continue;
  // Sentence-initial adverbs ("Fortunately") are not names.
  if (word.length > 4 && word.endsWith("ly")) continue;
  proper.add(word);
}

const sorted = [...proper].sort();
const OUT = path.join(__dirname, "../src/data/proper-nouns.ts");
const lines = sorted.map((word) => `  "${word}",`).join("\n");

const content = `/**
 * Proper nouns dominant in SUBTLEX-US subtitles (capitalized more often than
 * lowercase): given names, surnames, places, titles, shows. Generated by
 * scripts/generate-proper-nouns.mjs. Do not hand-edit.
 *
 * NGSL headwords, curriculum days/months/numbers, and a small everyday-English
 * keep list are excluded so "web", "hope", "hey", "captain" stay learnable.
 */
export const PROPER_NOUNS: ReadonlySet<string> = new Set([
${lines}
]);
`;

fs.writeFileSync(OUT, content, "utf8");
