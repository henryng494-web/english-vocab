/**
 * Regenerate src/data/spoken-frequency-ranks.ts from subtlex-word-frequencies.
 * Run: node scripts/generate-subtlex-ranks.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const subtlex = require("subtlex-word-frequencies");

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, "../src/data/spoken-frequency-ranks.ts");
const MAX_RANK = 5000;

/** Skip subtitle noise: single letters and non-alpha tokens. */
function isLearnableWord(word) {
  return /^[a-z]+$/.test(word) && word.length > 1;
}

const wordToRank = new Map();
let duplicates = 0;

for (let i = 0; i < subtlex.length; i++) {
  const word = subtlex[i].word.toLowerCase();
  const subtlexRank = i + 1;
  if (wordToRank.has(word)) {
    duplicates++;
    continue;
  }
  wordToRank.set(word, subtlexRank);
}

const entries = [...wordToRank.entries()]
  .filter(([word]) => isLearnableWord(word))
  .sort((a, b) => a[1] - b[1]);

const lines = entries.map(([word, rank]) => `  "${word}": ${rank},`);

const content = `/**
 * Spoken-English frequency ranks from SUBTLEX-US (movie/TV subtitles).
 *
 * Source: subtlex-word-frequencies 2.0.0 (ISC), which republishes the
 * SUBTLEX-US corpus by Brysbaert & New. Rank = position in the SUBTLEX
 * frequency list (1 = most frequent). Generated by scripts/generate-subtlex-ranks.mjs.
 *
 * Includes all learnable lowercase words from the full SUBTLEX-US list.
 * Do not hand-edit — regenerate instead.
 */
export const SPOKEN_FREQUENCY_RANKS: Readonly<Record<string, number>> = {
${lines.join("\n")}
};

/** Highest SUBTLEX rank stored in this file. */
export const SUBTLEX_MAX_RANK = ${entries.length > 0 ? entries[entries.length - 1][1] : 0};

/** Target rank ceiling for the core learning inventory (rank 1–5000). */
export const SUBTLEX_CORE_RANK_LIMIT = ${MAX_RANK};
`;

fs.writeFileSync(OUT, content, "utf8");

console.log(`Wrote ${entries.length} words to ${OUT}`);
console.log(`Skipped ${duplicates} duplicate lowercase forms`);
console.log(`Learnable words with subtlex rank <= ${MAX_RANK}:`, entries.filter(([, r]) => r <= MAX_RANK).length);
